def evaluate_bm25_vs_sem(retriever_by_qid, k=5):
    rows = []
    for nama_q, q_text in queries.items():
        retrieved = retriever_by_qid(nama_q, q_text)
        p, r, f1, ap = calculate_metrics(retrieved, relevance_bm25_sem[q_text], k)
        rows.append({
            "query": nama_q,
            "jumlah_rel": len(relevance_bm25_sem[q_text]),
            "P@5": p,
            "R@5": r,
            "F1@5": f1,
            "MAP@5": ap
        })
    df_eval = pd.DataFrame(rows)
    rata = df_eval[["P@5", "R@5", "F1@5", "MAP@5"]].mean()
    df_eval.loc[len(df_eval)] = ["RATA-RATA", "-", *rata.values]
    return df_eval.round(4)

