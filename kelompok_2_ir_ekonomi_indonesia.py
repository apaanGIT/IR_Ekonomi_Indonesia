"""### 1.3 Standarisasi tanggal
Ada empat format tanggal. Selain itu **sebagian sel tanggal Kompas terbaca Excel sebagai `mm/dd`** sehingga hari dan bulan tertukar. URL Kompas memuat tanggal asli (`/read/YYYY/MM/DD/…`), jadi dipakai sebagai acuan koreksi.
"""

BULAN = {"jan":1,"feb":2,"mar":3,"apr":4,"mei":5,"may":5,"jun":6,"jul":7,"agu":8,"agt":8,"aug":8,
         "sep":9,"okt":10,"oct":10,"nov":11,"des":12,"dec":12}

def parse_date(v):
    if isinstance(v, pd.Timestamp): return v.normalize()
    s = str(v).strip()
    m = re.match(r"(\d{1,2})/(\d{1,2})/(\d{4})", s)                       # Kompas: dd/mm/yyyy
    if m: return pd.Timestamp(int(m[3]), int(m[2]), int(m[1]))
    m = re.match(r"(\d{1,2})\s+([A-Za-z]{3})[a-z]*\s+(\d{4})", s)         # IDN Times: 03 Sep 2026, 23:04 WIB
    if m and m[2].lower() in BULAN: return pd.Timestamp(int(m[3]), BULAN[m[2].lower()], int(m[1]))
    try: return pd.Timestamp(s).normalize()                               # ISO / format lain
    except Exception: return pd.NaT

def tanggal_standar(row):
    m = re.search(r"/read/(\d{4})/(\d{2})/(\d{2})/", str(row["url"]))
    if row["prefix"] == "KMP" and m:
        return pd.Timestamp(int(m[1]), int(m[2]), int(m[3]))
    return parse_date(row["date"])

df["date_std"] = df.apply(tanggal_standar, axis=1)
# sel yang terbaca Excel sebagai tanggal (bukan teks 'dd/mm/yyyy') = hari & bulan tertukar
df["tanggal_ditukar"] = [(r.prefix == "KMP" and not re.match(r"\d{1,2}/\d{1,2}/\d{4}", str(r.date)))
                         for r in df.itertuples()]
print("Tanggal gagal di-parse:", df["date_std"].isna().sum())
print("Tanggal Kompas yang tertukar (dikoreksi via URL):", df["tanggal_ditukar"].sum())
df.loc[df["tanggal_ditukar"], ["doc_id", "date", "date_std"]]

"""## 2. Pembersihan Noise per Media
Teks hasil scraping mengandung boilerplate yang berbeda di tiap media. Pembersihan dijalankan pada **teks asli** (huruf besar/kecil dan newline masih ada) dan menghasilkan `text_clean`, yang dipakai untuk cuplikan hasil pencarian dan semantic search.

### 2.1 Aturan pembersihan
| Media | Noise yang dibuang |
|---|---|
| IDN Times | menu navigasi, judul/tanggal, ringkasan AI "Intinya Sih", sidebar *Curated For You / Related Articles / Topics*, footer, sisipan iklan |
| Kompas.com | dateline, "Baca juga", "Lihat Foto" + caption, blok Artikel Kompas.id, "Baca berikutnya", ajakan donasi NTT, "Artikel ini pernah tayang di" |
| Liputan6 | dateline, "BACA JUGA", tombol "Perbesar" + caption, footer "Baca berita terkini…" |
| ANTARA | dateline, "Baca juga" |
"""

FN = (r"(?:persen|juta|miliar|ribu|dan|di|ke|yang|untuk|dari|pada|dengan|atau|akan|tak|tidak|ini|itu|oleh|bagi|"
      r"hingga|serta|sebagai|dalam|usai|jadi|jelang|meski|saat|bisa|ada)")
TITLE_WORD = rf"(?:[A-Z0-9\"“‘]\S*|{FN})"     # kata berhuruf kapital ala judul (Kompas memakai Title Case)

def clean_idn(t):
    t = re.sub(r"^.*?Intinya Sih", " ", t, count=1, flags=re.S)                        # menu + judul + tanggal
    t = re.sub(r"^.*?This section summary was AI-assisted and reviewed by our editorial team\.?\s*(?:Share Article)?",
               " ", t, count=1, flags=re.S)                                            # ringkasan AI
    t = re.sub(r"(?:\nShare Article|\nCurated For You|\nRelated Articles|\nTopics\n|IDN Times logo\s+About Us).*$",
               " ", t, flags=re.S)                                                     # sidebar + footer
    t = re.sub(r"Iklan - Scroll untuk Melanjutkan", " ", t)
    t = re.sub(r"\b[A-Za-z ]{3,20}, IDN Times\s*[-–—]", " ", t)                        # dateline
    return t

def clean_kmp(t):
    t = re.sub(r"^(?:[A-Z ]+,\s*)?KOMPAS\.com\s*-\s*", "", t.strip())                  # dateline
    t = re.sub(r"Saudara-saudara kita di Nusa Tenggara Timur.{0,400}?https?://\S+", " ", t, flags=re.S)  # ajakan donasi
    t = re.sub(r"Baca berikutnya.{0,200}$", " ", t, flags=re.S)
    t = re.sub(r"Artikel ini pernah tayang di.{0,500}$", " ", t, flags=re.S)
    t = re.sub(r"Sumber:\s*https?://\S+", " ", t)
    t = re.sub(r"Lihat Foto\s+[^()]{0,200}?(?:\((?:[^()]|\([^()]*\))*\)\.?\s?)+", " ", t)   # keterangan foto
    t = re.sub(rf"Baca juga\s*:\s*(?:{TITLE_WORD}\s+){{1,25}}", " ", t)                # judul 'Baca juga' (maks 25 kata)
    t = re.sub(rf"(?:{TITLE_WORD}\s+){{1,15}}Artikel Kompas\.id", " ", t)               # blok artikel Kompas.id
    return t

def clean_lp6(t):
    t = re.sub(r"Liputan6\.com,\s*[A-Za-z ]{3,25}\s*-\s*", " ", t)                     # dateline
    t = re.sub(r"BACA JUGA\s*:\s*\n[^\n]*\n?", " ", t)
    t = re.sub(r"FOTO:[^\n]*\n", " ", t)
    t = re.sub(r"Perbesar\s*\n[^\n]*\n?", " ", t)                                      # tombol zoom + keterangan foto
    t = re.sub(r"Baca berita terkini dan terpercaya di Berita Liputan6", " ", t)
    return t

def clean_ant(t):
    t = re.sub(r"^\s*[A-Za-z ]{3,25}\(ANTARA\)\s*-\s*", "", t)                         # dateline
    t = re.sub(r"Baca juga\s*:[^\n]*(?:\n|$)", " ", t)
    return t

CLEANERS = {"IDN": clean_idn, "KMP": clean_kmp, "LP6": clean_lp6, "ANT": clean_ant}

# keterangan foto satu baris yang diakhiri kredit fotografer, mis. "(IDN Times/Nama)"
CAPTION_LINE = re.compile(
    r"^[^\n]{0,250}\((?=[^()]*[A-Za-z])[^()]*(?:Liputan6|merdeka|IDN Times|Dok|Foto|FOTO|Antara|ANTARA|AFP|Reuters|"
    r"Shutterstock|SHUTTERSTOCK|pexels|unsplash)[^()]*\)[.\s]*$", re.M)
CAPTION_LINE2 = re.compile(r"^[^\n]{0,200}IDN Times/[^\n()]{1,40}$", re.M)

def clean_umum(t):
    t = CAPTION_LINE.sub(" ", t)
    t = CAPTION_LINE2.sub(" ", t)
    t = t.replace("\xa0", " ")
    t = re.sub(r"https?://\S+|www\.\S+", " ", t)
    return re.sub(r"\s+", " ", t).strip()

def bersihkan(prefix, teks):
    return clean_umum(CLEANERS[prefix](str(teks)))

"""### 2.2 Menerapkan pembersihan"""

df["text_raw"] = df["text"]
df["text_clean"] = [bersihkan(p, t) for p, t in zip(df["prefix"], df["text_raw"])]
df["len_raw"] = df["text_raw"].str.len()
df["len_clean"] = df["text_clean"].str.len()
