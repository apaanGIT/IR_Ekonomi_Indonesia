def calculate_metrics(retrieved, rel_set, k=5):
    """Menghitung Precision@k, Recall@k, F1@k, dan Average Precision (AP@k)."""
    retrieved_k = retrieved[:k]
    if not rel_set:
        return 0.0, 0.0, 0.0, 0.0

    hits = 0
    sum_precisions = 0.0
    for i, doc_id in enumerate(retrieved_k, start=1):
        if doc_id in rel_set:
            hits += 1
            sum_precisions += hits / i

    precision = hits / k if k > 0 else 0.0
    recall = hits / len(rel_set)
    f1 = (2 * precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
    ap = sum_precisions / min(len(rel_set), k)

    return precision, recall, f1, ap

