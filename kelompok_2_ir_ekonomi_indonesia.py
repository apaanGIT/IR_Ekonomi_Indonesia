# Fungsi Term Frequency Saturation
def satf(f, dl, avgdl, k1=1.5, b=0.75):

    K = k1 * (
        1 - b + b * dl / avgdl
    )

    return (
        f * (k1 + 1) /
        (f + K)
    )


# Fungsi perhitungan skor BM25
def bm25_score(
    query_terms,
    terms,
    smooth=True,
    k1=1.5,
    b=0.75
):

    counts = Counter(terms)
    score = 0.0

    for term in query_terms:

        if counts[term] > 0:

            score += (
                idf_bm25(term, smooth)
                * satf(
                    counts[term],
                    len(terms),
                    avgdl,
                    k1,
                    b
                )
            )

    return score


