"""### 8.5 Fungsi ranking"""

def rank_tfidf(query, idf_mode="smoothed", tf_mode="log", top_k=20):
    index = INDEXES[(idf_mode, tf_mode)]
    scores, _ = cosine_scores(query, index)

    hasil = pd.DataFrame({
        "doc_id": docs["doc_id"],
        "media": docs["media"],
        "title": docs["title"],
        "skor_tfidf": np.round(scores, 4),
    })
    hasil = hasil[hasil["skor_tfidf"] > 0]            # sama dengan BM25: skor 0 tidak ditampilkan
    hasil = hasil.sort_values("skor_tfidf", ascending=False).head(top_k).reset_index(drop=True)
    hasil.insert(0, "rank", hasil.index + 1)
    return hasil

