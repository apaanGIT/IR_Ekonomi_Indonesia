"""### 9.3 — Preprocessing (sama untuk ketiga metode)

`Case Folding → Hapus URL → Tokenisasi [a-z0-9]+ → Filtering angka → Stopword Removal`

- `tokenize()` dan `filtering()` **sama persis** dengan P12a, supaya token korpus Anda cocok dengan kosakata embedding.
- **Tanpa stemming**: embedding P12a dilatih pada kata yang tidak di-*stem* (misalnya *pemain*, bukan *main*). Jika korpus di-*stem*, banyak token tidak akan ditemukan di embedding. Agar perbandingan adil, CountVectorizer dan TF-IDF juga memakai token yang sama.
- Stopword removal memakai daftar Sastrawi seperti P3 (kata negasi dipertahankan).
"""

def case_folding(text: str) -> str:
    return text.lower()

def hapus_url(text: str) -> str:
    return re.sub(r"https?://\S+|www\.\S+", " ", text)

def tokenize(text: str) -> list[str]:          # sama dengan P12a
    return re.findall(r"[a-z0-9]+", text)

def filtering(tokens: list[str]) -> list[str]:  # sama dengan P12a
    return [t for t in tokens if not t.isdigit()]

KATA_NEGASI = {"tidak", "bukan", "jangan", "tanpa", "belum"}
STOPWORDS = set(StopWordRemoverFactory().get_stop_words()) - KATA_NEGASI

def stopword_removal(tokens: list[str]) -> list[str]:
    return [t for t in tokens if t not in STOPWORDS]

def preprocess_w2v(text: str, buang_stopword: bool = True) -> list[str]:   # <-- di-rename
    tokens = filtering(tokenize(hapus_url(case_folding(text))))
    return stopword_removal(tokens) if buang_stopword else tokens

