"""## 1. Pengelolaan Corpus
### 1.1 Konfigurasi & loader
Tiap file memakai `doc_id` yang bentrok (`D001` ada di tiga file, Liputan6 memakai `EK_001`), nama media tidak seragam, dan sheet Liputan6 bernama `Data`. Loader di bawah menyeragamkan semuanya: ID global `IDN_001`, `KMP_001`, `LP6_001`, `ANT_001`.
"""

MEDIA_CFG = {
    "IDN": {"media": "IDN Times",   "cari": "idntimes"},
    "KMP": {"media": "Kompas.com",  "cari": "kompas"},
    "LP6": {"media": "Liputan6",    "cari": "liputan6"},
    "ANT": {"media": "ANTARA",      "cari": "antara"},
}
TOPIK_STANDAR = "Ekonomi Indonesia"

def cari_file(kata):
    hit = [f for f in glob.glob("*.xlsx") if kata in f.lower()]
    assert hit, f"File dengan kata '{kata}' tidak ditemukan di folder kerja"
    return hit[0]

def load_one(prefix):
    path = cari_file(MEDIA_CFG[prefix]["cari"])
    x = pd.ExcelFile(path)
    sheet = "Corpus" if "Corpus" in x.sheet_names else x.sheet_names[0]   # Liputan6 memakai sheet 'Data'
    d = x.parse(sheet).dropna(subset=["text"]).copy()
    d["doc_id_asal"] = d["doc_id"].astype(str)
    d["doc_id"] = [f"{prefix}_{int(re.sub(r'[^0-9]', '', s)):03d}" for s in d["doc_id_asal"]]
    d["media_asal"] = d["media"].astype(str)
    d["media"] = MEDIA_CFG[prefix]["media"]
    d["topic_asal"] = d["topic"].astype(str)
    d["topic"] = TOPIK_STANDAR
    d["sumber_file"] = path
    d["prefix"] = prefix
    return d

"""### 1.2 Menggabungkan empat corpus"""

